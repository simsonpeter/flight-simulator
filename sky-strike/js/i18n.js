let current = 'nl';

export function detectLang() {
  const raw = (navigator.language || navigator.userLanguage || 'nl').toLowerCase();
  const two = raw.slice(0, 2);
  if (PACKS[raw]) return raw;
  if (PACKS[two]) return two;
  if (raw.startsWith('zh')) return 'zh';
  if (raw.startsWith('pt')) return 'pt';
  return 'nl';
}

export function setLang(id) {
  current = PACKS[id] ? id : 'en';
  document.documentElement.lang = current;
  document.documentElement.dir = RTL.has(current) ? 'rtl' : 'ltr';
  document.body?.classList.toggle('rtl', RTL.has(current));
  return current;
}

export function getLang() {
  return current;
}

export function tr(key, vars = {}) {
  const pack = PACKS[current] || EN;
  let str = pack[key] ?? EN[key] ?? key;
  Object.keys(vars).forEach((k) => {
    str = String(str).split(`{${k}}`).join(String(vars[k]));
  });
  return str;
}

export function applyI18n() {
  document.title = tr('gameName');
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    el.textContent = tr(el.dataset.i18n);
  });
  document.querySelectorAll('[data-i18n-html]').forEach((el) => {
    el.innerHTML = tr(el.dataset.i18nHtml);
  });
  document.querySelectorAll('[data-i18n-aria]').forEach((el) => {
    el.setAttribute('aria-label', tr(el.dataset.i18nAria));
  });
}

export function fillLanguageSelect(select, selected) {
  select.innerHTML = '';
  LANGUAGES.forEach((l) => {
    const opt = document.createElement('option');
    opt.value = l.id;
    opt.textContent = `${l.native}  ·  ${l.region}`;
    if (l.id === selected) opt.selected = true;
    select.appendChild(opt);
  });
}
